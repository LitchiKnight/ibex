"""Build-time generator for the tb side of the command-interface layout.

Renders ``py/cmd_defs.py`` (the single definition of the opcode numbers
and packed-argument bit positions) into an SV include file consumed by
``tb/ibex_cocotb_tb.sv``. The Makefile runs this before Verilator
elaboration, so the Python side and the tb can never hold different
numbers; the CMD_INIT layout fingerprint remains as a runtime sanity
check on top.

Usage: python3 gen/cmd_defs.py gen/out/cmd_defs.svh
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "py"))

import cmd_defs  # noqa: E402

HEADER = """\
// Generated by gen/cmd_defs.py from py/cmd_defs.py - do not edit.
// Command opcodes and packed-argument bit positions for
// tb/ibex_cocotb_tb.sv. The Python side imports the same numbers from
// py/cmd_defs.py, so the two copies can never drift; the CMD_INIT layout
// fingerprint stays as a runtime sanity check.
"""


def render() -> str:
    lines = [HEADER]
    for name, value in cmd_defs.OPCODES.items():
        lines.append(f"`define {name} 8'h{value:02x}")
    for group in (cmd_defs.STEP_BITS, cmd_defs.DSIDE_BITS,
                  cmd_defs.SETMIP_BITS):
        for name, value in group.items():
            lines.append(f"`define {name} {value}")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        raise SystemExit(1)
    out = Path(sys.argv[1])
    out.write_text(render())
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
